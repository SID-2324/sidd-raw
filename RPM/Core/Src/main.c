float compute_PID(PID_Controller *pid, float target, float measured) {
    pid->error = target - measured;

    // Anti-Windup: Only integrate if error is manageable
    if (pid->error > -50 && pid->error < 50) {
        pid->integral += pid->error;
    }

    // Cap the integral to prevent runaway
    float int_limit = pid->max_pwm / (pid->Ki + 0.001f);
    if (pid->integral > int_limit) pid->integral = int_limit;
    if (pid->integral < -int_limit) pid->integral = -int_limit;

    float derivative = pid->error - pid->last_error;
    float output = (pid->Kp * pid->error) + (pid->Ki * pid->integral) + (pid->Kd * derivative);

    pid->last_error = pid->error;
    return output;
}

void control_left(float pid_output) {
    uint16_t speed;
    float deadband = 120.0f; // Minimum PWM to overcome friction

    if (pid_output > 1.0f) { // Forward
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_10, GPIO_PIN_SET);
        speed = (uint16_t)(pid_output + deadband);
    }
    else if (pid_output < -1.0f) { // Reverse
        HAL_GPIO_WritePin(GPIOB, GPIO_PIN_10, GPIO_PIN_RESET);
        speed = (uint16_t)((-pid_output) + deadband);
    }
    else { // Dead stop
        speed = 0;
    }

    if (speed > 1000) speed = 1000; // Cap at ARR
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, speed);
}
