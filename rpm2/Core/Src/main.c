float Get_Actual_RPM(void) {
    int16_t current_count = __HAL_TIM_GET_COUNTER(&htim2);
    int16_t delta = current_count - encoder_prev_count;
    encoder_prev_count = current_count;

    // Calculate base RPM
    float rpm = ((float)delta / ENCODER_X4) / LOOP_TIME_SEC * 60.0f;

    // Apply software polarity fix if necessary
    if (INVERT_ENCODER) {
        rpm = -rpm;
    }
    return rpm;
}

float Compute_PID(float target, float actual, float kp, float ki, float kd) {
    float error = target - actual;

    // Proportional
    float p_term = kp * error;

    // Integral (with anti-windup clamping)
    pid_integral += error * LOOP_TIME_SEC;
    float i_term = ki * pid_integral;

    // Derivative
    float derivative = (error - pid_prev_error) / LOOP_TIME_SEC;
    float d_term = kd * derivative;
    pid_prev_error = error;

    // Total Output
    float output = p_term + i_term + d_term;

    // Clamp output strictly to 0% - 100% (Forward Only)
    if (output > 100.0f) {
        output = 100.0f;
        pid_integral -= error * LOOP_TIME_SEC; // Prevent integral ballooning
    } else if (output < 0.0f) {
        output = 0.0f;
        pid_integral -= error * LOOP_TIME_SEC;
    }

    return output;
}

void Command_Motor(float power_percent) {
    // Map 0.0 - 100.0% to MDDS10 Motor 1 Range: 64 (Stop) to 127 (Full Forward)
    uint8_t cmd_byte = 64 + (uint8_t)((power_percent / 100.0f) * 63.0f);

    // Transmit via UART1 to Motor Driver
    HAL_UART_Transmit(&huart1, &cmd_byte, 1, 2);
}
